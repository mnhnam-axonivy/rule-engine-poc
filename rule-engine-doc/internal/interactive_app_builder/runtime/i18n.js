export function normalizeLanguage() {
  return 'en';
}

export function createTranslator(lang, lessonStrings = {}) {
  const language = normalizeLanguage(lang);
  const sources = [lessonStrings[language], STRINGS[language]].filter(Boolean);
  return (key, params) => {
    let text = key;
    for (const source of sources) {
      if (source[key] !== undefined) { text = source[key]; break; }
    }
    if (!params) return text;
    return String(text).replace(/\{(\w+)\}/g, (m, name) => (params[name] === undefined ? m : params[name]));
  };
}
