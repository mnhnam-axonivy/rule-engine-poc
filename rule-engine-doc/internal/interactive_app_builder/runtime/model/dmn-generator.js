/**
 * "New DMN...": builds a ready-to-edit model from fields of the
 * process data, the way the connector does (rule-engine: DmnCreator, DmnSpec, DmnGenerator).
 *
 *   - one input per selected input field, named exactly like the field
 *   - one decision with a decision table: a column per input and output, one placeholder rule
 *   - a nested data class is unfolded into one column per simple field (member.type)
 *   - with a single output the decision is named like the output field, so its result is
 *     mapped by name; with several it is named like the model and returns a structure
 *   - a selection that the mapping by name would not find again is refused (readableByName)
 *   - the model says which fields it was generated from (origin): a later run of the same element
 *     uses it, any other file of that name is an error
 *
 * The simulation works on the model the file would contain, not on its XML.
 */
import { kindOf, feelTypeOf, toFeelName, typeOfPath, findField, normalize, MappingError } from './mapping.js';

const MAX_COLUMN_DEPTH = 3;
export const PLACEHOLDER_NOTE = 'Placeholder: matches everything. Add your rules above this one.';

/** The file name the connector uses for the wanted name, which is required. */
export function modelNameFor(wanted) {
  let name = String(wanted == null ? '' : wanted).trim();
  if (name.toLowerCase().endsWith('.dmn')) name = name.slice(0, -4);
  const safe = name.replace(/[^A-Za-z0-9._-]/g, '-').replace(/^[-._]+/, '');
  if (!safe) throw new MappingError("'New DMN name' is empty. Name the new DMN, e.g. member-discount.");
  return safe;
}

/** DmnCreator.origin: what a generated file says about the fields it was generated from. */
export function origin(inputs, outputs) {
  return 'Generated by a Business Rule Task. Inputs: ' + inputs.map(item => item.expression).join(', ') +
    '. Outputs: ' + outputs.map(item => item.expression).join(', ') + '.';
}

/** DmnCreator.generatedFrom: true if these fields generated the model, not another file of the same name. */
export function generatedFrom(dmn, inputs, outputs) {
  return Boolean(dmn && dmn.description === origin(inputs, outputs));
}

/** The result of the placeholder rule: a neutral value that is valid for the type. */
function placeholder(feelType) {
  if (feelType === 'number') return '0';
  if (feelType === 'string') return '""';
  if (feelType === 'boolean') return 'false';
  return 'null';
}

function columnsOf(field, classes) {
  const cls = classes[field.type];
  if (!cls) return [{ label: field.name, expression: field.name, type: feelTypeOf(field.type, classes) }];
  const columns = [];
  const unfold = (path, current, depth) => {
    current.fields.forEach(sub => {
      const subPath = path + '.' + toFeelName(sub.name);
      const nested = classes[sub.type];
      if (nested) {
        if (depth < MAX_COLUMN_DEPTH) unfold(subPath, nested, depth + 1);
      } else if (kindOf(sub.type, classes) !== 'list') {
        columns.push({ label: subPath, expression: subPath, type: feelTypeOf(sub.type, classes) });
      }
    });
  };
  unfold(field.name, cls, 1);
  return columns.length ? columns : [{ label: field.name, expression: field.name, type: '' }];
}

/**
 * @param {Object} options
 * @param {string} options.modelName  wanted name of the model (the file name)
 * @param {{ name: string, expression: string }[]} options.inputs   selected input fields
 * @param {{ name: string, expression: string }[]} options.outputs  selected output fields
 * @param {{ dataClass: Object, classes: Object }} model  the process data the paths belong to
 * @returns {Object} a model as parseDmn returns it, with `generated: true`
 * @throws {MappingError} when the selection is incomplete or a field does not exist
 */
export function generateDmn({ modelName, inputs, outputs }, model) {
  if (!inputs.length || !outputs.length) {
    throw new MappingError("To create a new DMN, select at least one input field and one output field, e.g. inputs 'in.member.purchaseAmount, in.member.type' and outputs 'in.member.discount'.");
  }
  const name = modelNameFor(modelName);
  const typed = selection => selection.map(item => {
    if (!/^in(\.[A-Za-z_$][\w$]*)+$/.test(item.expression)) {
      throw new MappingError("'" + item.expression + "' is no field. List fields with their path, like in.member.purchaseAmount: each becomes an input or an output named like its field.");
    }
    const type = typeOfPath(model, item.expression);
    if (type === null) {
      throw new MappingError("The field '" + item.expression + "' does not exist in " + model.dataClass.name + '. List fields with their path, like in.member.purchaseAmount.');
    }
    return { name: toFeelName(item.name), type };
  });
  const inputFields = typed(inputs);
  const outputFields = typed(outputs);

  let decision = outputFields.length === 1 ? outputFields[0].name : toFeelName(name[0].toLowerCase() + name.slice(1));
  if (inputFields.some(input => input.name === decision)) decision += 'Result';

  const columns = [];
  inputFields.forEach(field => columnsOf(field, model.classes).forEach(column => columns.push(column)));
  const outputColumns = outputFields.map(field => ({ name: field.name, label: field.name, type: feelTypeOf(field.type, model.classes) }));
  const resultType = outputColumns.length === 1 ? outputColumns[0].type : 't' + decision[0].toUpperCase() + decision.slice(1);

  return {
    model: name,
    file: 'dmn/' + name + '.dmn',
    name,
    namespace: 'https://axonivy.com/dmn/' + name,
    description: origin(inputs, outputs),
    generated: true,
    types: {},
    inputs: inputFields.map(field => ({ id: '_input_' + field.name, name: field.name, type: model.classes[field.type] ? 't' + model.classes[field.type].simpleName : feelTypeOf(field.type, model.classes) })),
    decisions: [{
      id: '_decision_' + decision,
      name: decision,
      type: resultType,
      description: '',
      requires: { inputs: inputFields.map(field => '_input_' + field.name), decisions: [] },
      kind: 'table',
      expression: '',
      table: {
        hitPolicy: 'FIRST',
        inputs: columns,
        outputs: outputColumns,
        rules: [{ inputs: columns.map(() => '-'), outputs: outputColumns.map(column => placeholder(column.type)), annotation: PLACEHOLDER_NOTE }]
      }
    }]
  };
}

/**
 * DmnCreator.readableByName: the Business Rule Task reads the inputs and writes the results of a
 * generated DMN by name, like those of any other. A selection that the mapping by name would not
 * find again is refused, before there is a file.
 * @throws {MappingError}
 */
export function readableByName(inputs, outputs, model) {
  const clash = outputs.find(output => inputs.some(input => input.name === output.name));
  if (clash) {
    throw new MappingError("'" + clash.name + "' is selected as input and as output. A decision cannot read and fill the same name: choose another field for the result.");
  }
  inputs.concat(outputs).forEach(({ name, expression }) => {
    const field = expression.slice(expression.lastIndexOf('.') + 1);
    if (normalize(name) !== normalize(field)) {
      throw new MappingError("Several selected fields are named '" + field + "'. The Business Rule Task finds a field by its name, so it could only read one of them: select fields with different names.");
    }
    const found = findField(model, name);
    if (!found) {
      throw new MappingError('The Business Rule Task finds a field by its name, up to 4 levels below in, and would not find ' + expression + ': select a field closer to in.');
    }
    if (found.expression !== expression) {
      throw new MappingError('The Business Rule Task finds a field by its name and would use ' + found.expression + " for '" + name + "', not " + expression +
        ', because it comes first. Select ' + found.expression + ', or give one of the fields another name.');
    }
  });
}
