/**
 * The tutorial of the Axon Ivy Rules Engine: an overview with the path of steps, and one page per
 * step, rendered from Markdown that the dialog Tutorial.xhtml puts on the page.
 *
 * The overview lists the steps in order, from easy to hard. Each row has the sections of its page
 * as links, a "Play" button for its walkthrough and a small ▶ on every section that is a chapter of
 * the walkthrough, which plays from there.
 *
 * A page with an interactive walkthrough gets a "Walkthrough" button next to its title. A part of a
 * page can have one of its own instead, with its button next to the heading of the part. The
 * walkthroughs are js/interactive-runtime.min.js (window.reInteractive) and one js/guide-NN.js per
 * page, or js/guide-NN-<n>.js for the n-th ## part of page NN, all generated by
 * internal/interactive_app_builder.
 */
(function() {

  /** The pages in reading order. The titles are also what [Title] links in the Markdown refer to. */
  var PAGES = [
    { id: '01', title: 'What is DMN?' },
    { id: '02', title: 'How the rule engine works' },
    { id: '03', title: 'Set up and run your first decision' },
    { id: '04', title: 'Use an existing DMN decision' },
    { id: '05', title: 'Create a new DMN from scratch' },
    { id: '06', title: 'Change rules without deployment' },
    { id: '07', title: 'Edit rules in the Portal' },
    { id: '08', title: 'Handle errors' },
    { id: '09', title: 'Run it in production' },
    { id: '10', title: 'Several decisions and the Java API' },
    // in groups; its questions are in the contents, below their group
    { id: '11', title: 'Frequently asked questions', tocDepth: 3 }
  ];

  /** Sections that only point onwards: not listed on the overview. */
  var NOT_LISTED = ['See also', 'What comes next'];

  var TEXT = {
    back: '← All steps',
    onThisPage: 'On this page',
    walkthrough: 'Walkthrough',
    play: 'Play',
    playFrom: 'Play the walkthrough from here',
    read: 'Read',
    close: 'Close',
    previous: 'Previous',
    next: 'Next'
  };

  var currentPage = null;

  function pageById(id) {
    for (var i = 0; i < PAGES.length; i++) if (PAGES[i].id === id) return PAGES[i];
    return null;
  }

  // ── Walkthrough ──────────────────────────────────────────────────────────────
  // The simulation of a page plays in a full-screen dialog and is released again when the
  // dialog closes, which frees its WebGL context.
  var walkthrough = null; // { dialog, handle, previousFocus, onKey, overflow } while the dialog is open

  function lessonExists(lessonId) {
    return Boolean(window.reInteractive && window.reInteractive.has(lessonId));
  }

  /**
   * The walkthroughs of a page: guide-NN belongs to its title, guide-NN-n to its n-th ## heading.
   * @return [{ id, part }] with part 0 for the title, in the order of the page
   */
  function lessonsOf(pageId) {
    var lessons = [];
    if (lessonExists('guide-' + pageId)) lessons.push({ id: 'guide-' + pageId, part: 0 });
    var prefix = 'guide-' + pageId + '-';
    var ids = window.reInteractive && typeof window.reInteractive.ids === 'function' ? window.reInteractive.ids() : [];
    ids.filter(function(id) { return id.indexOf(prefix) === 0 && /^\d+$/.test(id.slice(prefix.length)); })
      .map(function(id) { return { id: id, part: Number(id.slice(prefix.length)) }; })
      .sort(function(a, b) { return a.part - b.part; })
      .forEach(function(lesson) { lessons.push(lesson); });
    return lessons;
  }

  function about(lessonId) {
    return window.reInteractive && typeof window.reInteractive.about === 'function' ? window.reInteractive.about(lessonId) : null;
  }

  /**
   * @param lessonId the walkthrough to play, guide-NN when left out
   * @param part the heading of its part, if any
   * @param chapter the index of the chapter to start with; the first when left out
   */
  function openWalkthrough(pageId, lessonId, part, chapter) {
    lessonId = lessonId || 'guide-' + pageId;
    if (walkthrough || !lessonExists(lessonId)) return;
    var page = pageById(pageId);
    var dialog = document.createElement('div');
    dialog.className = 're-walkthrough';
    dialog.setAttribute('role', 'dialog');
    dialog.setAttribute('aria-modal', 'true');
    dialog.setAttribute('aria-label', TEXT.walkthrough);
    var bar = document.createElement('div');
    bar.className = 're-walkthrough-bar';
    var title = document.createElement('span');
    title.className = 're-walkthrough-title';
    title.textContent = (page ? page.title + (part ? ' · ' + part : '') + ' — ' : '') + TEXT.walkthrough;
    var close = document.createElement('button');
    close.type = 'button';
    close.className = 're-walkthrough-close';
    close.setAttribute('aria-label', TEXT.close);
    close.title = TEXT.close + ' (Esc)';
    close.textContent = '✕';
    close.onclick = closeWalkthrough;
    bar.appendChild(title);
    bar.appendChild(close);
    var stage = document.createElement('div');
    stage.className = 're-walkthrough-stage';
    dialog.appendChild(bar);
    dialog.appendChild(stage);
    document.body.appendChild(dialog);

    var onKey = function(e) {
      if (e.key === 'Escape' && !e.defaultPrevented) closeWalkthrough();
    };
    document.addEventListener('keydown', onKey);
    walkthrough = { dialog: dialog, handle: null, previousFocus: document.activeElement, onKey: onKey, overflow: document.documentElement.style.overflow };
    document.documentElement.style.overflow = 'hidden';
    try {
      walkthrough.handle = window.reInteractive.mount(stage, lessonId, { autoplay: true, chapter: chapter || 0 });
    } catch (e) {
      if (window.console) console.error('The walkthrough could not be started.', e);
      closeWalkthrough();
      return;
    }
    close.focus();
  }

  function closeWalkthrough() {
    if (!walkthrough) return;
    var w = walkthrough;
    walkthrough = null;
    document.removeEventListener('keydown', w.onKey);
    if (w.handle) w.handle.dispose();
    w.dialog.remove();
    document.documentElement.style.overflow = w.overflow;
    if (w.previousFocus && w.previousFocus.focus) w.previousFocus.focus();
  }

  // ── Rendering a page ─────────────────────────────────────────────────────────

  function markdownOf(id) {
    var source = document.getElementById('re-md-' + id);
    return source ? source.textContent.trim() : '';
  }

  /**
   * [Handle errors] in the Markdown becomes a link to that page. A bracket that never closes on its line, such as
   * the FEEL range [500..1000), is no link and must not swallow the text up to the next ].
   */
  function linkPages(md) {
    return md.replace(/\[([^\[\]\n]+)\](?!\s*[\(\[])/g, function(match, text) {
      for (var i = 0; i < PAGES.length; i++) {
        if (PAGES[i].title === text) return '[' + text + '](page:' + PAGES[i].id + ')';
      }
      return match;
    });
  }

  function renderMarkdown(md) {
    if (!window.marked) return '<pre>' + md.replace(/&/g, '&amp;').replace(/</g, '&lt;') + '</pre>';
    var renderer = new marked.Renderer();
    renderer.link = function(token) {
      var href = token.href;
      if (href && href.indexOf('page:') === 0) {
        return '<a href="javascript:void(0)" onclick="showPage(\'' + href.slice(5) + '\')" class="re-page-link">' + token.text + '</a>';
      }
      var title = token.title ? ' title="' + token.title + '"' : '';
      return '<a href="' + href + '"' + title + ' target="_blank" rel="noopener">' + token.text + '</a>';
    };
    marked.setOptions({ renderer: renderer, gfm: true, breaks: false });
    return marked.parse(md);
  }

  function renderPage(id) {
    var md = markdownOf(id);
    var page = pageById(id);
    if (!md) md = '# ' + (page ? page.title : id) + '\n\n> This page has no content. Check that the CMS of the project contains /Tutorial/guide-' + id + '.';
    var article = document.getElementById('re-article');
    article.innerHTML = renderMarkdown(linkPages(md));

    if (window.hljs) {
      article.querySelectorAll('pre code').forEach(function(block) {
        if (!block.classList.contains('hljs')) hljs.highlightElement(block);
      });
    }
    addWalkthroughButtons(id);
    addPager(id);
    buildToc(id);
  }

  /**
   * Puts a "Walkthrough" button next to the page title when the page has a simulation, or next to
   * the heading of each part that has one.
   */
  function addWalkthroughButtons(id) {
    var parts = document.querySelectorAll('#re-article h2');
    lessonsOf(id).forEach(function(lesson) {
      var heading = lesson.part ? parts[lesson.part - 1] : document.querySelector('#re-article h1');
      if (!heading) return;
      var row = document.createElement('div');
      row.className = lesson.part ? 're-title-row re-part-row' : 're-title-row';
      heading.parentNode.insertBefore(row, heading);
      row.appendChild(heading);
      var button = document.createElement('button');
      button.type = 'button';
      button.className = 're-walkthrough-btn';
      button.setAttribute('data-walkthrough', lesson.id);
      button.innerHTML = '<span class="re-walkthrough-play" aria-hidden="true">▶</span>';
      button.appendChild(document.createTextNode(TEXT.walkthrough));
      button.setAttribute('aria-haspopup', 'dialog');
      button.onclick = function() { openWalkthrough(id, lesson.id, lesson.part ? heading.textContent : ''); };
      row.appendChild(button);
    });
  }

  /** Previous and next step, at the end of the page. */
  function addPager(id) {
    var index = PAGES.indexOf(pageById(id));
    if (index < 0) return;
    var pager = document.createElement('div');
    pager.className = 're-pager';
    var link = function(page, label, className) {
      var a = document.createElement('a');
      a.className = 're-pager-link ' + className;
      a.href = 'javascript:void(0)';
      a.onclick = function() { showPage(page.id); };
      var small = document.createElement('span');
      small.className = 're-pager-label';
      small.textContent = label;
      var title = document.createElement('span');
      title.className = 're-pager-title';
      title.textContent = page.title;
      a.appendChild(small);
      a.appendChild(title);
      return a;
    };
    if (index > 0) pager.appendChild(link(PAGES[index - 1], '← ' + TEXT.previous, 'previous'));
    if (index < PAGES.length - 1) pager.appendChild(link(PAGES[index + 1], TEXT.next + ' →', 'next'));
    document.getElementById('re-article').appendChild(pager);
  }

  /** The contents: the ## headings, and on a page with tocDepth 3 the ### headings below each of them. */
  function buildToc(id) {
    var toc = document.getElementById('re-toc');
    if (!toc) return;
    var page = pageById(id);
    var deep = Boolean(page && page.tocDepth === 3);
    var html = '<a class="re-sidebar-back" href="javascript:void(0)" onclick="showIndex()">' + TEXT.back + '</a>';
    var headings = document.querySelectorAll(deep ? '#re-article h2, #re-article h3' : '#re-article h2');
    if (headings.length) {
      html += '<h4>' + TEXT.onThisPage + '</h4><ul>';
      var item = false; // the <li> of a ## heading is open
      var nested = false; // the list of its ### headings is open
      headings.forEach(function(heading, i) {
        heading.id = 're-section-' + i;
        var link = '<a href="#re-section-' + i + '"></a>';
        if (heading.tagName === 'H3' && item) {
          if (!nested) { html += '<ul>'; nested = true; }
          html += '<li>' + link + '</li>';
          return;
        }
        if (nested) { html += '</ul>'; nested = false; }
        if (item) html += '</li>';
        html += '<li>' + link;
        item = true;
      });
      html += (nested ? '</ul>' : '') + (item ? '</li>' : '') + '</ul>';
    }
    toc.innerHTML = html;
    // set as text, so a heading can never be read as markup
    var links = toc.querySelectorAll('ul a');
    headings.forEach(function(heading, i) { links[i].textContent = heading.textContent; });
  }

  // ── Navigation ───────────────────────────────────────────────────────────────

  /**
   * @param target where to scroll to: the text of a ## or ### heading of the page, or the number of a ## heading,
   *        e.g. 2 for the second part; none: the top
   */
  function showPage(id, target) {
    if (!pageById(id)) return;
    currentPage = id;
    document.getElementById('view-index').style.display = 'none';
    document.getElementById('view-detail').style.display = 'block';
    window.scrollTo(0, 0);
    renderPage(id);
    var heading = null;
    if (typeof target === 'number') {
      heading = document.querySelectorAll('#re-article h2')[target - 1] || null;
    } else if (target) {
      document.querySelectorAll('#re-article h2, #re-article h3').forEach(function(candidate) {
        if (!heading && candidate.textContent === target) heading = candidate;
      });
    }
    if (heading) heading.scrollIntoView({ block: 'start' });
  }

  function showIndex() {
    currentPage = null;
    document.getElementById('view-detail').style.display = 'none';
    document.getElementById('view-index').style.display = 'block';
    window.scrollTo(0, 0);
  }

  // ── The path on the overview ─────────────────────────────────────────────────

  function element(tag, className, text) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    if (text) node.textContent = text;
    return node;
  }

  /** The ## headings of a page, read from its Markdown: code blocks are skipped. */
  function sectionsOf(id) {
    var sections = [];
    var inCode = false;
    markdownOf(id).split('\n').forEach(function(line) {
      if (/^\s*```/.test(line)) inCode = !inCode;
      else if (!inCode && /^## /.test(line)) sections.push(line.slice(3).trim());
    });
    return sections;
  }

  function playButton(label, onclick) {
    var button = element('button', 're-walkthrough-btn re-step-play');
    button.type = 'button';
    button.setAttribute('aria-haspopup', 'dialog');
    button.innerHTML = '<span class="re-walkthrough-play" aria-hidden="true">▶</span>';
    button.appendChild(document.createTextNode(label));
    button.onclick = onclick;
    return button;
  }

  /**
   * Turns each row of the path, which the dialog renders with the title and the description of its page, into a
   * step: its number, the sections of the page as links, Play and Read. A section that is a chapter of a walkthrough
   * gets a ▶ that plays from that chapter; a part with a walkthrough of its own gets one that plays it.
   */
  function renderSteps() {
    document.querySelectorAll('.re-step[data-page]').forEach(function(row) {
      var id = row.getAttribute('data-page');
      var page = pageById(id);
      if (!page || row.getAttribute('data-ready')) return;
      row.setAttribute('data-ready', 'true');
      var titleNode = row.querySelector('.re-step-title');
      var descNode = row.querySelector('.re-step-desc');
      var title = titleNode ? titleNode.textContent.trim() : page.title;
      var desc = descNode ? descNode.textContent.trim() : '';
      row.textContent = '';

      row.appendChild(element('div', 're-step-num', id));
      var main = element('div', 're-step-main');
      var link = element('a', 're-step-title', title);
      link.href = 'javascript:void(0)';
      link.onclick = function() { showPage(id); };
      main.appendChild(link);
      if (desc) main.appendChild(element('p', 're-step-desc', desc));

      var lessons = lessonsOf(id);
      var main0 = lessons.length && lessons[0].part === 0 ? lessons[0] : null;
      var chapters = main0 && about(main0.id) ? about(main0.id).chapters : [];
      var all = sectionsOf(id);
      var list = element('ul', 're-step-sections');
      all.forEach(function(section, index) {
        if (NOT_LISTED.indexOf(section) >= 0) return;
        var item = element('li', 're-step-section');
        item.setAttribute('data-section', section);
        var go = element('a', 're-step-section-link', section);
        go.href = 'javascript:void(0)';
        go.onclick = function() { showPage(id, section); };
        item.appendChild(go);
        var chapter = chapters.indexOf(section);
        var part = null;
        lessons.forEach(function(lesson) { if (lesson.part === index + 1) part = lesson; });
        if (chapter >= 0 || part) {
          var from = element('button', 're-step-chapter-play', '▶');
          from.type = 'button';
          from.title = TEXT.playFrom;
          from.setAttribute('aria-label', TEXT.playFrom + ': ' + section);
          from.setAttribute('data-walkthrough', part ? part.id : main0.id);
          from.setAttribute('data-chapter', String(part ? 0 : chapter));
          from.onclick = part
            ? function() { openWalkthrough(id, part.id, section, 0); }
            : function() { openWalkthrough(id, main0.id, '', chapter); };
          item.appendChild(from);
        }
        list.appendChild(item);
      });
      main.appendChild(list);
      row.appendChild(main);

      var actions = element('div', 're-step-actions');
      var first = main0 || lessons[0];
      if (first) {
        var info = about(first.id);
        var partTitle = first.part ? all[first.part - 1] : '';
        var play = playButton(TEXT.play, function() { openWalkthrough(id, first.id, partTitle, 0); });
        play.setAttribute('data-walkthrough', first.id);
        actions.appendChild(play);
        if (info && info.duration) actions.appendChild(element('span', 're-step-duration', info.duration));
      }
      var read = element('a', 're-step-read', TEXT.read + ' →');
      read.href = 'javascript:void(0)';
      read.onclick = function() { showPage(id); };
      actions.appendChild(read);
      row.appendChild(actions);
    });
  }

  document.addEventListener('DOMContentLoaded', renderSteps);

  window.showPage = showPage;
  window.showIndex = showIndex;
  window.openWalkthrough = openWalkthrough;
  window.closeWalkthrough = closeWalkthrough;
  window.reTutorial = { pages: PAGES, current: function() { return currentPage; } };

})();
