  @Test
  void diagramLayout_hasAShapeForEveryNode() {
    var spec = new DmnSpec("layout",
        List.of(DmnField.of("a", DmnType.NUMBER), DmnField.of("b", DmnType.NUMBER), DmnField.of("c", DmnType.NUMBER)),
        List.of(DmnField.of("d", DmnType.NUMBER)));
    String dmn = generator.generate(spec);
    assertThat(dmn.split("<dmndi:DMNShape ", -1)).as("3 inputs and 1 decision").hasSize(5);
    assertThat(dmn.split("<dmndi:DMNEdge ", -1)).as("an edge per input").hasSize(4);
    assertThat(dmn)
        .contains("<dc:Bounds x=\"60\" y=\"300\" width=\"160\" height=\"80\"/>")
        .contains("<dc:Bounds x=\"260\" y=\"300\" width=\"160\" height=\"80\"/>")
        .contains("<dc:Bounds x=\"460\" y=\"300\" width=\"160\" height=\"80\"/>")
        .contains("<dc:Bounds x=\"260\" y=\"80\" width=\"160\" height=\"80\"/>");
    validAndCompiled(dmn);
  }

  private CompiledModel validAndCompiled(String dmn) {
    List<Message> findings = compiler.validate(dmn);
    assertThat(findings)
        .as("findings of the DMN validator (schema, model, compilation) for%n%s", dmn)
        .isEmpty();
    return compiler.compile("generated", 1, dmn);
  }

  private Evaluation evaluate(CompiledModel model, Map<String, Object> input) {
    var evaluation = evaluator.evaluate(model, null, input);
    assertThat(evaluation.messages()).as("messages of the evaluation").isEmpty();
    return evaluation;
  }
