  @Test
  void fieldNamesReservedInFeel_areRenamed() {
    var reserved = List.of("and", "between", "else", "every", "external", "false", "for", "function", "if", "in",
        "instance", "not", "null", "of", "or", "return", "satisfies", "some", "then", "true");
    var inputs = new ArrayList<DmnField>();
    reserved.forEach(name -> inputs.add(DmnField.of(name, DmnType.STRING)));
    var spec = new DmnSpec("reserved", inputs, List.of(DmnField.of("result", DmnType.STRING)));
    assertThat(spec.inputs()).extracting(DmnField::name)
        .allSatisfy(name -> assertThat(name).endsWith("_"));

    var model = validAndCompiled(generator.generate(spec));
    var input = new HashMap<String, Object>();
    reserved.forEach(name -> input.put(FeelNames.toFeelName(name), name));
    assertThat(evaluate(model, input).results()).containsEntry("result", "");
    assertThat(FeelNames.toFieldName("function_")).isEqualTo("function");
    assertThat(FeelNames.toFieldName("total_")).isEqualTo("total_");
  }

  @Test
  void fieldNamesOfBuiltInFunctions_keepTheirName() {
    var builtIns = List.of("date", "time", "number", "string", "duration", "list", "context", "range", "min", "max",
        "sum", "count", "now", "today", "abs", "contains", "matches", "replace", "is", "day", "month", "year");
    var inputs = new ArrayList<DmnField>();
    builtIns.forEach(name -> inputs.add(DmnField.of(name, DmnType.STRING)));
    var spec = new DmnSpec("builtins", inputs, List.of(DmnField.of("result", DmnType.STRING)));
    assertThat(spec.inputs()).extracting(DmnField::name).containsExactlyElementsOf(builtIns);

    String dmn = generator.generate(spec);
    var model = validAndCompiled(dmn);
    var input = new HashMap<String, Object>();
    builtIns.forEach(name -> input.put(name, name));
    assertThat(evaluate(model, input).results()).containsEntry("result", "");

    // and the columns really read the fields: a rule on the column 'date' matches the value of the field 'date'
    String edited = dmn.replaceFirst("<text>-</text>", "<text>\"date\"</text>")
        .replace("<text>&quot;&quot;</text>", "<text>\"matched\"</text>");
    var editedModel = validAndCompiled(edited);
    assertThat(evaluate(editedModel, input).results()).containsEntry("result", "matched");
  }

  @Test
  void duplicateFieldNames_getUniqueNames() {
    var names = FeelNames.uniqueNames(List.of("in.member.type", "in.order.type", "in.member.name", "in.member.type",
        "in.total", "in.function"));
    assertThat(names).containsExactly(
        Map.entry("in.member.type", "memberType"),
        Map.entry("in.order.type", "orderType"),
        Map.entry("in.member.name", "name"),
        Map.entry("in.total", "total"),
        Map.entry("in.function", "function_"));
    assertThat(FeelNames.uniqueNames(List.of("in.a.b.type", "in.c.b.type")))
        .containsExactly(Map.entry("in.a.b.type", "aBType"), Map.entry("in.c.b.type", "cBType"));

    var inputs = new ArrayList<DmnField>();
    names.values().forEach(name -> inputs.add(DmnField.of(name, DmnType.STRING)));
    var model = validAndCompiled(generator.generate(new DmnSpec("duplicates", inputs,
        List.of(DmnField.of("ok", DmnType.BOOLEAN)))));
    assertThat(model.inputs()).extracting(LoadedVersion.Input::name)
        .containsExactlyInAnyOrder("memberType", "orderType", "name", "total", "function_");

    assertThatThrownBy(() -> new DmnSpec("duplicates",
        List.of(DmnField.of("type", DmnType.STRING), DmnField.of("type", DmnType.STRING)),
        List.of(DmnField.of("ok", DmnType.BOOLEAN))))
        .isInstanceOf(IllegalArgumentException.class)
        .hasMessageContaining("Duplicate input field name 'type'");
  }

