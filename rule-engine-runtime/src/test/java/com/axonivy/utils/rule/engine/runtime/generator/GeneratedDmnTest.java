  @Test
  void javaTypes_areMapped() {
    var mapper = new JavaTypeMapper();
    assertThat(mapper.toDmnType(String.class)).isEqualTo(DmnType.STRING);
    assertThat(mapper.toDmnType(int.class)).isEqualTo(DmnType.NUMBER);
    assertThat(mapper.toDmnType(Number.class)).isEqualTo(DmnType.NUMBER);
    assertThat(mapper.toDmnType(BigDecimal.class)).isEqualTo(DmnType.NUMBER);
    assertThat(mapper.toDmnType(Boolean.class)).isEqualTo(DmnType.BOOLEAN);
    assertThat(mapper.toDmnType(LocalDate.class)).isEqualTo(DmnType.DATE);
    assertThat(mapper.toDmnType(LocalDateTime.class)).isEqualTo(DmnType.DATE_TIME);
    assertThat(mapper.toDmnType(java.util.Date.class)).isEqualTo(DmnType.DATE_TIME);
    assertThat(mapper.toDmnType(java.time.Duration.class)).isEqualTo(DmnType.DAYS_TIME_DURATION);
    assertThat(mapper.toDmnType(Object.class)).isEqualTo(DmnType.ANY);
    assertThat(mapper.toDmnType(Map.class)).isEqualTo(DmnType.ANY);
    assertThat(mapper.toDmnType(String[].class)).isEqualTo(new DmnType.Collection(DmnType.STRING));
    assertThat(mapper.toDmnType(byte[].class)).isEqualTo(DmnType.ANY);

    var member = (DmnType.Structure) mapper.toDmnType(Member.class);
    assertThat(member.name()).isEqualTo("tMember");
    assertThat(member.fields()).extracting(DmnField::name)
        .as("fields in declaration order")
        .containsExactly("customerId", "type", "purchaseAmount", "vip", "since", "address", "tags",
            "otherAddresses", "referredBy");
    assertThat(member.fields().get(1).type()).isInstanceOf(DmnType.Enumeration.class);
    assertThat(member.fields().get(6).type()).isEqualTo(new DmnType.Collection(DmnType.STRING));
    assertThat(member.fields().get(8).type()).as("a recursive reference ends as Any").isEqualTo(DmnType.ANY);
  }

